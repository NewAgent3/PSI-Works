    # ============================================================ commands
    def cmd_new(self):
        if not self._confirm_discard():
            return
        self.scene = new_default_scene()
        self.scene_path = None
        self.selected_index = None
        self._load_camera_into_vars()
        self._refresh_list()
        self._redraw_canvas()
        self._load_props_into_vars()

    def cmd_open(self):
        path = filedialog.askopenfilename(filetypes=[("JSON scene", "*.json"),
                                                      ("All", "*.*")])
        if not path:
            return
        try:
            with open(path, "r", encoding="utf-8") as f:
                self.scene = json.load(f)
        except Exception as e:
            messagebox.showerror("Open failed", str(e))
            return
        self.scene_path = path
        self.selected_index = None
        self._load_camera_into_vars()
        self._refresh_list()
        self._redraw_canvas()
        self._load_props_into_vars()

    def cmd_save(self):
        if not self.scene_path:
            return self.cmd_save_as()
        self._sync_render_vars_into_scene()
        try:
            with open(self.scene_path, "w", encoding="utf-8") as f:
                json.dump(self.scene, f, indent=2)
        except Exception as e:
            messagebox.showerror("Save failed", str(e))

    def cmd_save_as(self):
        path = filedialog.asksaveasfilename(defaultextension=".json",
                                            filetypes=[("JSON scene", "*.json")])
        if not path:
            return
        self.scene_path = path
        self.cmd_save()

    def cmd_add_sphere(self):
        self.scene["spheres"].append(new_sphere(0, 1, 0, 1.0, "lambert"))
        self.selected_index = len(self.scene["spheres"]) - 1
        self._refresh_list(); self._redraw_canvas(); self._load_props_into_vars()

    def cmd_add_light(self):
        s = new_sphere(0, 5, 0, 1.0, "light")
        self.scene["spheres"].append(s)
        self.selected_index = len(self.scene["spheres"]) - 1
        self._refresh_list(); self._redraw_canvas(); self._load_props_into_vars()

    def cmd_add_glass(self):
        s = new_sphere(0, 1, 0, 1.0, "dielectric")
        self.scene["spheres"].append(s)
        self.selected_index = len(self.scene["spheres"]) - 1
        self._refresh_list(); self._redraw_canvas(); self._load_props_into_vars()

    def cmd_delete(self):
        if self.selected_index is None:
            return
        del self.scene["spheres"][self.selected_index]
        self.selected_index = None
        self._refresh_list(); self._redraw_canvas(); self._load_props_into_vars()

    def cmd_duplicate(self):
        if self.selected_index is None:
            return
        s = dict(self.scene["spheres"][self.selected_index])
        s["x"] += 0.5; s["z"] += 0.5
        self.scene["spheres"].append(s)
        self.selected_index = len(self.scene["spheres"]) - 1
        self._refresh_list(); self._redraw_canvas(); self._load_props_into_vars()

    # ============================================================ render
    def cmd_render(self):
        # 1. pull all latest UI state into the data model
        self._sync_render_vars_into_scene()

        r = self.scene["render"]
        exe = r["exe"]
        if not os.path.isabs(exe):
            # try alongside the script first, then PATH
            here = os.path.dirname(os.path.abspath(__file__))
            candidate = os.path.join(here, exe)
            if os.path.exists(candidate):
                exe = candidate

        if not os.path.exists(exe):
            messagebox.showerror("Render",
                f"Pathtracer executable not found:\n  {exe}\n\n"
                "Set the correct path under 'Pathtracer exe' or place "
                "pathtracer.exe next to scene_maker.py.")
            return

        # 2. write the .scene file alongside the exe
        out_dir = os.path.dirname(os.path.abspath(exe))
        scene_file = os.path.join(out_dir, "current.scene")
        try:
            write_scene_file(self.scene, scene_file)
        except Exception as e:
            messagebox.showerror("Render", f"Failed to write scene file:\n{e}")
            return

        # 3. build CLI
        cmd = [exe,
               "--scene",     "custom",
               "--scenefile", scene_file,
               "--width",     str(int(r["width"])),
               "--height",    str(int(r["height"])),
               "--spp",       str(int(r["spp"])),
               "--depth",     str(int(r["depth"])),
               "--threads",   str(int(r["threads"])),
               "--output",    r["output"]]
        seed = int(r["seed"])
        if seed:
            cmd += ["--seed", str(seed)]

        # 4. launch in a background thread so the UI stays responsive
        self.btn_render.config(state="disabled", text="Rendering…")
        self.render_status.config(text="Rendering – this may take a while…",
                                  foreground="#aa6")

        def worker():
            try:
                proc = subprocess.run(cmd, cwd=out_dir,
                                      capture_output=True, text=True)
                ok = proc.returncode == 0
                msg = proc.stdout[-400:] if proc.stdout else ""
                err = proc.stderr[-400:] if proc.stderr else ""
            except Exception as e:
                ok, msg, err = False, "", str(e)

            def finish():
                self.btn_render.config(state="normal", text="▶  RENDER")
                if ok:
                    out = os.path.join(out_dir, r["output"])
                    self.render_status.config(
                        text=f"Done. Saved {out}", foreground="#0a0")
                    if messagebox.askyesno("Render finished",
                            f"Saved {out}\n\nOpen image?"):
                        self._open_file(out)
                else:
                    self.render_status.config(text="Render failed.",
                                              foreground="#c33")
                    messagebox.showerror("Render failed",
                        f"Command:\n  {' '.join(cmd)}\n\n"
                        f"stdout:\n{msg}\n\nstderr:\n{err}\n\n"
                        "Tip: the original pathtracer.exe does NOT support "
                        "'--scene custom'. Rebuild from the patched "
                        "pathtracer.c included in this package.")
            self.after(0, finish)

        threading.Thread(target=worker, daemon=True).start()

    # ============================================================ events
    def _on_list_select(self, _evt):
        sel = self.listbox.curselection()
        self.selected_index = sel[0] if sel else None
        self._redraw_canvas()
        self._load_props_into_vars()

    def _on_material_change(self):
        if self.selected_index is None:
            return
        s = self.scene["spheres"][self.selected_index]
        new_m = self.var_mat.get()
        if new_m != s["material"]:
            # reset to nice defaults for this material
            s.update(DEFAULT_MATERIAL[new_m])
            s["material"] = new_m
            self._load_props_into_vars()
        self._redraw_canvas(); self._refresh_list()

    def _on_prop_change(self):
        if self.selected_index is None:
            return
        s = self.scene["spheres"][self.selected_index]
        try:
            s["name"]   = self.var_name.get() or "sphere"
            s["x"]      = float(self.var_x.get())
            s["y"]      = float(self.var_y.get())
            s["z"]      = float(self.var_z.get())
            s["radius"] = max(0.001, float(self.var_radius.get()))
            s["r"]      = float(self.var_r.get())
            s["g"]      = float(self.var_g.get())
            s["b"]      = float(self.var_b.get())
            s["fuzz"]   = float(self.var_fuzz.get())
            s["ir"]     = float(self.var_ir.get())
        except (ValueError, tk.TclError):
            return
        self._redraw_canvas(); self._refresh_list()

    def _on_pick_color(self):
        if self.selected_index is None:
            return
        s = self.scene["spheres"][self.selected_index]
        init = "#{:02x}{:02x}{:02x}".format(
            int(min(s["r"], 1) * 255), int(min(s["g"], 1) * 255),
            int(min(s["b"], 1) * 255))
        c = colorchooser.askcolor(initialcolor=init, title="Pick albedo")
        if c and c[0]:
            r, g, b = c[0]
            s["r"], s["g"], s["b"] = r / 255.0, g / 255.0, b / 255.0
            self.var_r.set(s["r"]); self.var_g.set(s["g"]); self.var_b.set(s["b"])
            self._redraw_canvas(); self._refresh_list()

    def _on_cam_change(self):
        try:
            self.scene["camera"]["lookfrom"] = [
                float(self.cam_vars["lf_x"].get()),
                float(self.cam_vars["lf_y"].get()),
                float(self.cam_vars["lf_z"].get())]
            self.scene["camera"]["lookat"] = [
                float(self.cam_vars["la_x"].get()),
                float(self.cam_vars["la_y"].get()),
                float(self.cam_vars["la_z"].get())]
            self.scene["camera"]["vfov"]     = float(self.cam_vars["vfov"].get())
            self.scene["camera"]["aperture"] = float(self.cam_vars["aperture"].get())
            self.scene["camera"]["focus"]    = float(self.cam_vars["focus"].get())
            self.scene["sky"] = self.var_sky.get()
        except (ValueError, tk.TclError):
            return
        self._redraw_canvas()

    # ------------------------------------------------- canvas mouse handling
    def _on_canvas_click(self, evt):
        idx = self._pick(evt.x, evt.y)
        self.selected_index = idx
        if idx is not None:
            s = self.scene["spheres"][idx]
            self.drag_data = (evt.x, evt.y, s["x"], s["z"])
        else:
            self.drag_data = None
        self._refresh_list_selection()
        self._redraw_canvas()
        self._load_props_into_vars()

    def _on_canvas_drag(self, evt):
        if self.selected_index is None or self.drag_data is None:
            return
        x0, y0, sx0, sz0 = self.drag_data
        dx_world = (evt.x - x0) / self._scale()
        dz_world = (evt.y - y0) / self._scale()
        s = self.scene["spheres"][self.selected_index]
        s["x"] = sx0 + dx_world
        s["z"] = sz0 + dz_world
        self.var_x.set(round(s["x"], 4))
        self.var_z.set(round(s["z"], 4))
        self._redraw_canvas(); self._refresh_list()

    def _on_canvas_release(self, _evt):
        self.drag_data = None

    def _on_canvas_rclick(self, evt):
        wx, wz = self._canvas_to_world(evt.x, evt.y)
        self.scene["spheres"].append(new_sphere(wx, 1.0, wz, 0.5, "lambert"))
        self.selected_index = len(self.scene["spheres"]) - 1
        self._refresh_list(); self._redraw_canvas(); self._load_props_into_vars()

    # ============================================================ helpers
    def _apply_preset(self, w, h, spp, depth):
        self.rend_vars["width"].set(str(w))
        self.rend_vars["height"].set(str(h))
        self.rend_vars["spp"].set(str(spp))
        self.rend_vars["depth"].set(str(depth))

    def _browse_exe(self):
        path = filedialog.askopenfilename(
            title="Locate pathtracer executable",
            filetypes=[("Executables", "*.exe"), ("All", "*.*")])
        if path:
            self.rend_vars["exe"].set(path)

    def _open_file(self, path):
        try:
            if sys.platform.startswith("win"):
                os.startfile(path)  # type: ignore[attr-defined]
            elif sys.platform == "darwin":
                subprocess.run(["open", path])
            else:
                subprocess.run(["xdg-open", path])
        except Exception:
            pass

    def _confirm_discard(self):
        return messagebox.askyesno("Discard scene?",
            "Discard current scene and start a new one?")

    def _scale(self):
        return self.CANVAS_W / (2.0 * self.WORLD_HALF)

    def _world_to_canvas(self, x, z):
        s = self._scale()
        cx = self.CANVAS_W * 0.5 + x * s
        cy = self.CANVAS_H * 0.5 + z * s
        return cx, cy

    def _canvas_to_world(self, cx, cy):
        s = self._scale()
        return (cx - self.CANVAS_W * 0.5) / s, (cy - self.CANVAS_H * 0.5) / s

    def _pick(self, cx, cy):
        # nearest sphere within its projected radius (ignoring huge ground sphere)
        best_i, best_d = None, 1e9
        for i, s in enumerate(self.scene["spheres"]):
            if s["radius"] > 50:   # ground / cornell walls — don't pick
                continue
            sx, sy = self._world_to_canvas(s["x"], s["z"])
            d = math.hypot(cx - sx, cy - sy)
            r_pix = max(4.0, s["radius"] * self._scale())
            if d <= r_pix and d < best_d:
                best_d = d; best_i = i
        return best_i

    def _sync_render_vars_into_scene(self):
        for key in self.scene["render"]:
            v = self.rend_vars[key].get().strip()
            if key in ("width", "height", "spp", "depth", "threads", "seed"):
                try:
                    self.scene["render"][key] = int(v)
                except ValueError:
                    pass
            else:
                self.scene["render"][key] = v

    # ----- panel sync -----
    def _load_camera_into_vars(self):
        cam = self.scene["camera"]
        self.cam_vars["lf_x"].set(cam["lookfrom"][0])
        self.cam_vars["lf_y"].set(cam["lookfrom"][1])
        self.cam_vars["lf_z"].set(cam["lookfrom"][2])
        self.cam_vars["la_x"].set(cam["lookat"][0])
        self.cam_vars["la_y"].set(cam["lookat"][1])
        self.cam_vars["la_z"].set(cam["lookat"][2])
        self.cam_vars["vfov"].set(cam["vfov"])
        self.cam_vars["aperture"].set(cam["aperture"])
        self.cam_vars["focus"].set(cam["focus"])
        self.var_sky.set(self.scene.get("sky", "blue"))

    def _load_props_into_vars(self):
        if self.selected_index is None:
            self.var_name.set("")
            return
        s = self.scene["spheres"][self.selected_index]
        self.var_name.set(s.get("name", "sphere"))
        self.var_mat.set(s["material"])
        self.var_x.set(s["x"]); self.var_y.set(s["y"]); self.var_z.set(s["z"])
        self.var_radius.set(s["radius"])
        self.var_r.set(s.get("r", 0.7))
        self.var_g.set(s.get("g", 0.7))
        self.var_b.set(s.get("b", 0.7))
        self.var_fuzz.set(s.get("fuzz", 0.0))
        self.var_ir.set(s.get("ir", 1.5))

    def _refresh_list(self):
        self.listbox.delete(0, tk.END)
        for i, s in enumerate(self.scene["spheres"]):
            self.listbox.insert(tk.END,
                f"{i:02d}  {s.get('name','sphere'):<12} "
                f"[{s['material'][:4]}] r={s['radius']:.2f}")
        self._refresh_list_selection()

    def _refresh_list_selection(self):
        self.listbox.selection_clear(0, tk.END)
        if self.selected_index is not None:
            self.listbox.selection_set(self.selected_index)
            self.listbox.see(self.selected_index)

    # ============================================================ canvas
    def _redraw_canvas(self):
        c = self.canvas
        c.delete("all")
        # grid
        s = self._scale()
        for i in range(-int(self.WORLD_HALF), int(self.WORLD_HALF) + 1):
            x = self.CANVAS_W * 0.5 + i * s
            y = self.CANVAS_H * 0.5 + i * s
            col = "#3a3a40" if i != 0 else "#666"
            c.create_line(x, 0, x, self.CANVAS_H, fill=col)
            c.create_line(0, y, self.CANVAS_W, y, fill=col)

        c.create_text(self.CANVAS_W - 30, self.CANVAS_H * 0.5 - 8,
                      text="+X", fill="#888", font=("Segoe UI", 9, "bold"))
        c.create_text(self.CANVAS_W * 0.5 + 12, self.CANVAS_H - 12,
                      text="+Z", fill="#888", font=("Segoe UI", 9, "bold"))

        # spheres
        for i, sp in enumerate(self.scene["spheres"]):
            if sp["radius"] > 50:  # ground/walls ignored visually
                continue
            cx, cy = self._world_to_canvas(sp["x"], sp["z"])
            rp = max(3.0, sp["radius"] * s)
            mat = sp["material"]
            if mat == "lambert":
                fill = self._rgb_hex(sp["r"], sp["g"], sp["b"])
                outline = "#fff" if i == self.selected_index else "#000"
            elif mat == "metal":
                fill = self._rgb_hex(sp["r"], sp["g"], sp["b"])
                outline = "#fff" if i == self.selected_index else "#aaa"
            elif mat == "dielectric":
                fill = ""  # hollow circle
                outline = "#9cf"
            else:  # light
                fill = "#ffe680"
                outline = "#ff0"
            c.create_oval(cx - rp, cy - rp, cx + rp, cy + rp,
                          fill=fill, outline=outline,
                          width=2 if i == self.selected_index else 1)
            label = sp.get("name", "")
            if label:
                c.create_text(cx, cy - rp - 8, text=label, fill="#ddd",
                              font=("Segoe UI", 8))

        # camera marker
        cam = self.scene["camera"]
        lfx, lfy = self._world_to_canvas(cam["lookfrom"][0], cam["lookfrom"][2])
        lax, lay = self._world_to_canvas(cam["lookat"][0],   cam["lookat"][2])
        c.create_oval(lfx - 5, lfy - 5, lfx + 5, lfy + 5,
                      fill="#3a7afe", outline="#fff")
        c.create_line(lfx, lfy, lax, lay, fill="#3a7afe", arrow="last", width=2)
        c.create_text(lfx + 10, lfy - 10, text="cam", fill="#9bf",
                      font=("Segoe UI", 8, "bold"))

    @staticmethod
    def _rgb_hex(r, g, b):
        r = max(0.0, min(1.0, r)); g = max(0.0, min(1.0, g)); b = max(0.0, min(1.0, b))
        return "#{:02x}{:02x}{:02x}".format(int(r * 255), int(g * 255), int(b * 255))


