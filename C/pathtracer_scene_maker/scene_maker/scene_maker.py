# ---------------------------------------------------------------------------
#  .scene file format (very small, line-based, human readable)
# ---------------------------------------------------------------------------
#
#   # comments start with #
#   sky <blue|studio|black|sunset>
#   camera lookfrom <x> <y> <z>
#   camera lookat   <x> <y> <z>
#   camera vup      <x> <y> <z>
#   camera vfov     <deg>
#   camera aperture <a>
#   camera focus    <dist>            (0 = auto)
#   sphere lambert    <x> <y> <z> <r> <cr> <cg> <cb>
#   sphere metal      <x> <y> <z> <r> <cr> <cg> <cb> <fuzz>
#   sphere dielectric <x> <y> <z> <r> <ir>
#   sphere light      <x> <y> <z> <r> <er> <eg> <eb>
#
# The patched pathtracer.c (shipped alongside) parses this format when
# you pass --scene custom --scenefile scene.scene.

def write_scene_file(scene, path):
    cam = scene["camera"]
    lines = []
    lines.append("# PathTracer++ custom scene file")
    lines.append("# generated by scene_maker.py")
    lines.append(f"sky {scene.get('sky', 'blue')}")
    lines.append("camera lookfrom {:.6f} {:.6f} {:.6f}".format(*cam["lookfrom"]))
    lines.append("camera lookat   {:.6f} {:.6f} {:.6f}".format(*cam["lookat"]))
    lines.append("camera vup      {:.6f} {:.6f} {:.6f}".format(*cam["vup"]))
    lines.append(f"camera vfov     {cam['vfov']:.6f}")
    lines.append(f"camera aperture {cam['aperture']:.6f}")
    lines.append(f"camera focus    {cam['focus']:.6f}")
    for s in scene["spheres"]:
        m = s["material"]
        if m == "lambert":
            lines.append("sphere lambert {x:.6f} {y:.6f} {z:.6f} {radius:.6f} "
                         "{r:.6f} {g:.6f} {b:.6f}".format(**s))
        elif m == "metal":
            lines.append("sphere metal {x:.6f} {y:.6f} {z:.6f} {radius:.6f} "
                         "{r:.6f} {g:.6f} {b:.6f} {fuzz:.6f}".format(**s))
        elif m == "dielectric":
            lines.append("sphere dielectric {x:.6f} {y:.6f} {z:.6f} "
                         "{radius:.6f} {ir:.6f}".format(**s))
        elif m == "light":
            lines.append("sphere light {x:.6f} {y:.6f} {z:.6f} {radius:.6f} "
                         "{r:.6f} {g:.6f} {b:.6f}".format(**s))
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


