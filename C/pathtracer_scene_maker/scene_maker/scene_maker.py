"""
Scene Maker for PathTracer++
-----------------------------
A GUI scene editor that lets you visually place spheres, lights and the
camera, then hit "Render" to invoke pathtracer.exe with a custom scene.

Pipeline:
  1. Edit scene in the GUI (top-down XZ viewport + properties panel).
  2. Save scene to a .scene text file.
  3. Click Render -> writes scene.scene + invokes pathtracer.exe with
     `--scene custom --scenefile scene.scene` (requires the patched
     pathtracer.c included with this package; the original exe will
     still work for the 4 built-in scenes).

Tested with Python 3.8+ on Windows. No third-party dependencies.
"""

